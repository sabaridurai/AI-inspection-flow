CREATE TABLE inspections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email VARCHAR(320) NOT NULL REFERENCES app_users(email) ON DELETE CASCADE,
    client_id VARCHAR(100) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inspections_user_client UNIQUE (user_email, client_id)
);

CREATE TABLE inspection_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email VARCHAR(320) NOT NULL,
    inspection_client_id VARCHAR(100) NOT NULL,
    evidence_id VARCHAR(100) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    media_type VARCHAR(255) NOT NULL,
    content BYTEA NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inspection_evidence_user_item UNIQUE (user_email, inspection_client_id, evidence_id),
    CONSTRAINT fk_inspection_evidence_record FOREIGN KEY (user_email, inspection_client_id)
        REFERENCES inspections(user_email, client_id) ON DELETE CASCADE
);
